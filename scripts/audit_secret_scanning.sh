#!/usr/bin/env bash
# Audits GitHub Secret Scanning, Secret Push Protection, and open secret
# scanning alerts across the candidate repositories (Issues #65, #72).
#
# Usage:
#   ./scripts/audit_secret_scanning.sh                 # all candidate repos in oss-slu
#   ./scripts/audit_secret_scanning.sh repo1 repo2     # specific repos only
#   ORG=<user-or-org> OUT=<file> ./scripts/audit_secret_scanning.sh <repo>
#                                                      # e.g. validate on your own test repo/fork
#
# Output: docs/audits/secret_scanning_compliance_matrix_fall2026.md (override with OUT=)
#
# Requires: gh CLI, authenticated (gh auth login).
# Security settings and alerts are only returned to repository admins or
# organization security managers. For any other caller GitHub redacts the data,
# and this script reports "Permission Required" for that repository.

set -uo pipefail

ORG="${ORG:-oss-slu}"
OUT="${OUT:-docs/audits/secret_scanning_compliance_matrix_fall2026.md}"

REPOS=(
  civickit
  core_desk
  cv_zebrafish
  dads
  DigitalBoneBox
  enroll-dash
  geo-enricher
  GradEval360
  lrda_mobile
  lrda_website
  material-derailleur
  mechatronics-vr
  mithridatium
  oss_dev_analytics
  oss-orb
  oss-slu.github.io
  pao_surgery_simulator
  PilotDataSynchronization
  repoexplorer
  SpeechTranscription
  shelter_volunteers
  TheHealthApp
  TULIP
)

if [[ $# -gt 0 ]]; then
  REPOS=("$@")
fi

if ! command -v gh >/dev/null 2>&1; then
  echo "Error: GitHub CLI (gh) is not installed." >&2
  exit 1
fi
if ! gh auth status >/dev/null 2>&1; then
  echo "Error: gh is not authenticated. Run 'gh auth login' first." >&2
  exit 1
fi

fmt_status() {
  case "$1" in
    enabled)  echo "Enabled" ;;
    disabled) echo "Disabled" ;;
    *)        echo "Not Available" ;;
  esac
}

mkdir -p "$(dirname "$OUT")"

{
  echo "# Secret Scanning & Push Protection Compliance Matrix — Fall 2026"
  echo
  echo "Issue: #65"
  echo "Organization: \`$ORG\`"
  echo "Audit date: $(date +%Y-%m-%d)"
  echo "Generated by: \`scripts/audit_secret_scanning.sh\`"
  echo
  echo "| # | Repository | Secret Scanning Status | Push Protection Status | Open Alerts Count | Action Taken / Date Remediated |"
  echo "|---|------------|------------------------|------------------------|-------------------|--------------------------------|"
} > "$OUT"

i=0
compliant=0
needs_fix=0
no_permission=0
not_found=0

for repo in "${REPOS[@]}"; do
  i=$((i + 1))

  # 1. Repository settings (security_and_analysis is null for non-admin callers)
  if ! info=$(gh api "repos/$ORG/$repo" \
      --jq '[(.security_and_analysis != null),
             (.security_and_analysis.secret_scanning.status // "none"),
             (.security_and_analysis.secret_scanning_push_protection.status // "none")] | @tsv' 2>/dev/null); then
    ss="Repository Not Found"; pp="Repository Not Found"; alerts="N/A"
    action="Check repository name / access"
    not_found=$((not_found + 1))

  elif [[ "$(cut -f1 <<< "$info")" != "true" ]]; then
    ss="Permission Required"; pp="Permission Required"; alerts="Permission Required"
    action="Re-run with admin / security manager access"
    no_permission=$((no_permission + 1))

  else
    ss=$(fmt_status "$(cut -f2 <<< "$info")")
    pp=$(fmt_status "$(cut -f3 <<< "$info")")

    # 2. Open secret scanning alerts (GitHub returns 404 when scanning is disabled)
    if states=$(gh api --paginate "repos/$ORG/$repo/secret-scanning/alerts?state=open&per_page=100" \
        --jq '.[].state' 2>/dev/null); then
      alerts=$(grep -c '^open$' <<< "$states")
    else
      alerts="N/A"
    fi

    if [[ "$ss" == "Enabled" && "$pp" == "Enabled" && "$alerts" == "0" ]]; then
      action="None required"
      compliant=$((compliant + 1))
    else
      action="Pending remediation"
      needs_fix=$((needs_fix + 1))
    fi
  fi

  echo "| $i | \`$repo\` | $ss | $pp | $alerts | $action |" >> "$OUT"
  printf '%-26s secret_scanning=%-20s push_protection=%-20s open_alerts=%s\n' "$repo" "$ss" "$pp" "$alerts"
done

{
  echo
  echo "**Summary:** $compliant compliant, $needs_fix pending remediation, $no_permission permission required, $not_found not found (of ${#REPOS[@]} repositories)."
} >> "$OUT"

echo
echo "Matrix written to $OUT"
echo "Compliant: $compliant | Pending remediation: $needs_fix | Permission required: $no_permission | Not found: $not_found"